const removeID library.ID = "ps_00000000000000000000000C51"

func denyingRepo(t *testing.T) string {
	t.Helper()
	root := repo(t)
	write(t, root, ".promptstor/permissions/no-remove.yaml",
		"promptstor:\n  id: "+string(removeID)+"\ndeny_commands:\n  - rm\n")
	write(t, root, ".claude/settings.json", `{"permissions": {"deny": ["Bash(rm *)"]}}`+"\n")
	write(t, root, ".codex/rules/promptstor.rules",
		"# Generated by PromptStor. Do not edit.\n"+
			"prefix_rule(pattern=[\"rm\"], decision=\"forbidden\", justification=\"promptstor: no-remove\")\n")
	write(t, root, ".cursor/cli.json", `{"permissions": {"deny": ["Shell(rm)"]}}`+"\n")
	return root
}

func acknowledge(t *testing.T, root, tool string, id library.ID, hash string) {
	t.Helper()
	if hash == "" {
		items, err := library.LoadLayer(filepath.Join(root, ".promptstor"), library.LayerProject, library.LoadOptions{})
		if err != nil {
			t.Fatal(err)
		}
		for _, it := range items {
			if it.ID == id {
				hash = library.ContentHash(it)
			}
		}
	}
	path := filepath.Join(root, ".promptstor", "acks.json")
	acks, err := policy.LoadAcks(path)
	if err != nil {
		t.Fatal(err)
	}
	acks.Add(policy.Ack{ItemID: id, Tool: tool, Hash: hash})
	if err := acks.Save(path); err != nil {
		t.Fatal(err)
	}
}

func TestCheckCIAcceptsProjectAck(t *testing.T) {
	root := denyingRepo(t)

	code, out := check(t, root)

	if code != 1 {
		t.Fatalf("code %d, output:\n%s", code, out)
	}
	wantAll(t, out, "blocked: cursor: no-remove: not enforced in the Cursor editor\n", "2 problems\n")

	acknowledge(t, root, adapter.Cursor, removeID, "")
	code, out = check(t, root)

	if code != 1 {
		t.Fatalf("code %d, output:\n%s", code, out)
	}
	wantAll(t, out, "blocked: gemini-cli: no-remove: ", "1 problem\n")

	acknowledge(t, root, adapter.GeminiCLI, removeID, "")
	code, out = check(t, root)

	if code != 0 {
		t.Fatalf("code %d, output:\n%s", code, out)
	}
	wantAll(t, out, "note: cursor: no-remove: acknowledged: not enforced in the Cursor editor\n", "in sync\n")
}

func TestCheckCIIgnoresAckThatDoesNotMatch(t *testing.T) {
	tests := map[string]struct{ tool, hash string }{
		"older content": {adapter.Cursor, "older"},
		"other tool":    {adapter.Codex, ""},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			root := denyingRepo(t)
			acknowledge(t, root, test.tool, removeID, test.hash)

			code, out := check(t, root)

			if code != 1 {
				t.Fatalf("code %d, output:\n%s", code, out)
			}
			wantAll(t, out, "blocked: cursor: no-remove: not enforced in the Cursor editor\n")
		})
	}
}

func TestCheckCIRejectsUnusableAcks(t *testing.T) {
	tests := map[string]func(t *testing.T, root string){
		"not JSON": func(t *testing.T, root string) { write(t, root, ".promptstor/acks.json", "{not valid") },
		"symlinked": func(t *testing.T, root string) {
			outside := filepath.Join(t.TempDir(), "acks.json")
			write(t, filepath.Dir(outside), "acks.json", `{"acks": []}`)
			if err := os.Symlink(outside, filepath.Join(root, ".promptstor", "acks.json")); err != nil {
				t.Fatal(err)
			}
		},
	}
	for name, arrange := range tests {
		t.Run(name, func(t *testing.T) {
			root := repo(t)
			arrange(t, root)

			var out bytes.Buffer
			code, err := ci.Check(root, &out)

			if code != 2 || err == nil || !strings.Contains(err.Error(), "acks.json") {
				t.Fatalf("code %d, error %v", code, err)
			}
		})
	}
}

func TestCheckCIFailsOnLiteralSecret(t *testing.T) {
	server := "promptstor:\n  id: ps_00000000000000000000000C14\ntransport: stdio\ncommand: example-docs-server\n"
	tests := map[string]struct{ layer, key string }{
		"env":      {server + "env:\n  EXAMPLE_TOKEN: " + secretValue + "\n", "env/EXAMPLE_TOKEN"},
		"argument": {server + "args:\n  - --api-key\n  - " + secretValue + "\n", "args"},
		"url": {
			"promptstor:\n  id: ps_00000000000000000000000C14\ntransport: http\nurl: https://example.test/mcp?token=" + secretValue + "\n",
			"url",
		},
		"header": {
			"promptstor:\n  id: ps_00000000000000000000000C14\ntransport: http\nurl: https://example.test/mcp\nheaders:\n  Authorization: Bearer " + secretValue + "\n",
			"headers/Authorization",
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			root := repo(t)
			write(t, root, ".promptstor/mcp/example-docs.yaml", test.layer)

			code, out := check(t, root)

			if code != 1 {
				t.Fatalf("code %d, output:\n%s", code, out)
			}
			wantAll(t, out, "literal secret in example-docs ("+test.key+"); use an env placeholder\n")
			if strings.Contains(out, secretValue) {
				t.Error("output holds the secret value")
			}
		})
	}
}

func TestCheckCIFailsOnLiteralSecretThatIsCommitted(t *testing.T) {
	root := repo(t)
	replace(t, root, ".promptstor/mcp/example-docs.yaml", "EXAMPLE_TOKEN:\n    ref: env:EXAMPLE_TOKEN", "EXAMPLE_TOKEN: "+secretValue)
	replace(t, root, ".mcp.json", "${EXAMPLE_TOKEN}", secretValue)
	replace(t, root, ".cursor/mcp.json", "${env:EXAMPLE_TOKEN}", secretValue)
	replace(t, root, ".gemini/settings.json", "${EXAMPLE_TOKEN}", secretValue)

	code, out := check(t, root)

	if code != 1 {
		t.Fatalf("code %d, output:\n%s", code, out)
	}
	wantAll(t, out, "literal secret in example-docs (env/EXAMPLE_TOKEN); use an env placeholder\n", "1 problem\n")
	if strings.Contains(out, secretValue) {
		t.Error("output holds the secret value")
	}
}
