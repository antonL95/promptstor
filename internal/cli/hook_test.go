const guardBinary = "/opt/promptstor/bin/promptstor"

func TestHookCommandBlocksOwnedFileWithExitTwo(t *testing.T) {
	env := cliHome(t)
	path := filepath.Join(env.Home, ".claude", "agents", "owned.md")
	m := manifest.Manifest{Version: 1}
	m.Put(manifest.Entry{Tool: "claude-code", Path: path, Root: env.Home, Unit: manifest.UnitFile, Hash: "x", Items: []library.ID{cliRuleID}, Written: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)})
	if err := os.MkdirAll(env.StateDir(), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := m.Save(env.ManifestPath()); err != nil {
		t.Fatal(err)
	}
	payload, err := json.Marshal(map[string]any{"cwd": env.Home, "hook_event_name": "PreToolUse", "tool_name": "Write", "tool_input": map[string]any{"file_path": path, "content": "x"}})
	if err != nil {
		t.Fatal(err)
	}
	d := deps(env)
	var stderr bytes.Buffer
	d.Stdin = bytes.NewReader(payload)
	d.Stderr = &stderr
	_, err = run(t, d, "hook", "claude-code")
	var exit ExitCode
	if !errors.As(err, &exit) || int(exit) != 2 {
		t.Fatalf("error %v, want exit code 2", err)
	}
	if !strings.HasPrefix(stderr.String(), path+" is generated by PromptStor.") || strings.Count(stderr.String(), "\n") != 1 {
		t.Errorf("stderr %q", stderr.String())
	}
}

func TestHookCommandAllowsWithoutManifest(t *testing.T) {
	env := cliHome(t)
	d := deps(env)
	var stderr bytes.Buffer
	d.Stdin = strings.NewReader(`{"tool_name":"Write","tool_input":{"file_path":"/tmp/x","content":""}}`)
	d.Stderr = &stderr
	out, err := run(t, d, "hook", "claude-code")
	if err != nil || out != "" || stderr.Len() != 0 {
		t.Errorf("out %q stderr %q err %v", out, stderr.String(), err)
	}
}

func TestSyncInstallsEditGuardsWhenEnabled(t *testing.T) {
	env := cliHome(t)
	cfg := config.Config{Version: 1, Tools: []string{"claude-code", "opencode"}, EditGuards: true}
	if err := cfg.Save(env.ConfigFile()); err != nil {
		t.Fatal(err)
	}
	d := deps(env)
	d.Binary = guardBinary
	e, err := d.engine()
	if err != nil {
		t.Fatal(err)
	}
	var ids []library.ID
	for _, it := range e.Builtins {
		ids = append(ids, it.ID)
	}
	if len(ids) != 1 || ids[0] != library.EditGuard("claude-code", guardBinary).ID {
		t.Errorf("builtins %v, want the claude-code guard only, since nothing is wholly owned for opencode yet", ids)
	}
	cfg.EditGuards = false
	if err := cfg.Save(env.ConfigFile()); err != nil {
		t.Fatal(err)
	}
	if e, err = d.engine(); err != nil || len(e.Builtins) != 0 {
		t.Errorf("builtins %d with guards off, err %v", len(e.Builtins), err)
	}
}

func TestNoAntigravityGuardInstalled(t *testing.T) {
	env := cliHome(t)
	cfg := config.Config{Version: 1, Tools: []string{"antigravity"}, EditGuards: true}
	if err := cfg.Save(env.ConfigFile()); err != nil {
		t.Fatal(err)
	}
	d := deps(env)
	d.Binary = guardBinary
	e, err := d.engine()
	if err != nil {
		t.Fatal(err)
	}
	for _, it := range e.Builtins {
		if library.IsEditGuard(it) {
			t.Errorf("builtin %s installed for antigravity", it.ID)
		}
	}
	p, err := e.Plan("", plan.Options{})
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range p.Changes {
		if bytes.Contains(c.After, []byte("promptstor hook")) {
			t.Errorf("%s gets an edit guard", c.Path)
		}
	}
	want := adapter.Unsupported{Tool: "antigravity", Name: "edit guard antigravity", Reason: "Antigravity hooks must decide every call and have no neutral answer; no edit guard in this release"}
	if !slices.Contains(p.Unsupported, want) {
		t.Errorf("unsupported %+v, want %+v", p.Unsupported, want)
	}
}
