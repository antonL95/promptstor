package codex

import (
	"fmt"
	"path/filepath"
	"slices"
	"strings"
	"unicode/utf8"

	"github.com/antonL95/promptstor/internal/adapter"
	"github.com/antonL95/promptstor/internal/backup"
	"github.com/antonL95/promptstor/internal/library"
	"github.com/antonL95/promptstor/internal/manifest"
	"github.com/antonL95/promptstor/internal/plan"
)

const (
	maxSkillName       = 64
	generatedHeader    = "# Generated by PromptStor. Do not edit.\n"
	agentName          = "name"
	agentDescription   = "description"
	agentInstructions  = "developer_instructions"
	reasonSkillSummary = "Codex does not load a skill without a description"
	reasonSkillName    = "Codex limits skill names to 64 characters"
	reasonNoCommands   = "Codex has no project commands"
	reasonCredential   = "skill file %s matches the credential exclusion list"
	reasonAgentFields  = "Codex needs a description and instructions for a subagent"
	reasonAgentText    = "the subagent is not valid UTF-8"
	reasonAgentDropped = "written without %s, which Codex agent files do not take"
)

var agentSettings = []struct{ meta, field string }{
	{"codex_model", "model"},
	{"model_reasoning_effort", "model_reasoning_effort"},
	{"model_reasoning_summary", "model_reasoning_summary"},
	{"model_verbosity", "model_verbosity"},
}

func metaKeyOf(field string) (string, bool) {
	for _, setting := range agentSettings {
		if setting.field == field {
			return setting.meta, true
		}
	}
	return "", false
}

func (ex *exporter) skill(it library.Item) {
	units, ok := ex.skillUnits(it, it)
	if ok {
		ex.units = append(ex.units, units...)
	}
}

func (ex *exporter) skillUnits(it, as library.Item) ([]plan.Unit, bool) {
	switch {
	case strings.TrimSpace(as.Description) == "":
		ex.report(it, reasonSkillSummary)
		return nil, false
	case utf8.RuneCountInString(as.Name) > maxSkillName:
		ex.report(it, reasonSkillName)
		return nil, false
	}
	units, err := adapter.SkillUnits(ex.t, tool, as)
	if err != nil {
		ex.report(it, err.Error())
		return nil, false
	}
	for _, u := range units {
		if backup.Excluded(ex.t.Env, u.Path) {
			relative, _ := filepath.Rel(filepath.Join(ex.l.sharedSkills(), as.Name), u.Path)
			ex.report(it, fmt.Sprintf(reasonCredential, filepath.ToSlash(relative)))
			return nil, false
		}
	}
	return units, true
}

func (ex *exporter) command(it library.Item) {
	if ex.l.scope != adapter.ScopeUser {
		ex.report(it, reasonNoCommands)
		return
	}
	asSkill := it
	asSkill.Name, asSkill.Files = library.Slug(it.Name), nil
	if asSkill.Name == "" {
		ex.report(it, reasonNoFileName)
		return
	}
	units, ok := ex.skillUnits(it, asSkill)
	if !ok {
		return
	}
	for _, u := range units {
		u.Path, u.Root = ex.l.in(skillsDir, asSkill.Name, skillFile), ex.l.root
		ex.units = append(ex.units, u)
	}
}

func (ex *exporter) subagent(it library.Item) {
	slug := library.Slug(it.Name)
	switch {
	case slug == "":
		ex.report(it, reasonNoFileName)
		return
	case strings.TrimSpace(it.Description) == "" || strings.TrimSpace(it.Body) == "":
		ex.report(it, reasonAgentFields)
		return
	case !utf8.ValidString(it.Name + it.Description + it.Body):
		ex.report(it, reasonAgentText)
		return
	}
	var document strings.Builder
	document.WriteString(generatedHeader)
	fmt.Fprintf(&document, "%s = %s\n", agentName, tomlString(it.Name))
	fmt.Fprintf(&document, "%s = %s\n", agentDescription, tomlString(it.Description))
	fmt.Fprintf(&document, "%s = %s\n", agentInstructions, tomlMultiline(it.Body))
	var written []string
	for _, setting := range agentSettings {
		if value, ok := it.Meta[setting.meta].(string); ok && utf8.ValidString(value) {
			fmt.Fprintf(&document, "%s = %s\n", setting.field, tomlString(value))
			written = append(written, setting.meta)
		}
	}
	var dropped []string
	for _, key := range it.MetaKeys() {
		if key != agentName && key != agentDescription && !slices.Contains(written, key) {
			dropped = append(dropped, key)
		}
	}
	if len(dropped) > 0 {
		slices.Sort(dropped)
		ex.report(it, fmt.Sprintf(reasonAgentDropped, strings.Join(dropped, ", ")))
	}
	ex.add(plan.Unit{
		Path:    ex.l.in(agentsDir, slug+tomlExtension),
		Kind:    manifest.UnitFile,
		Content: []byte(document.String()),
		Items:   []library.ID{it.ID},
	})
}
