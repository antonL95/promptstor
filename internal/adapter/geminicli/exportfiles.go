package geminicli

import (
	"bytes"
	"fmt"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"

	"go.yaml.in/yaml/v3"

	"github.com/antonL95/promptstor/internal/adapter"
	"github.com/antonL95/promptstor/internal/backup"
	"github.com/antonL95/promptstor/internal/library"
	"github.com/antonL95/promptstor/internal/managed"
	"github.com/antonL95/promptstor/internal/manifest"
	"github.com/antonL95/promptstor/internal/plan"
)

const (
	generatedHeader        = "# Generated by PromptStor. Do not edit.\n"
	frontmatterFence       = "---\n"
	nameKey                = "name"
	reasonDropped          = "written without %s, which Gemini CLI %s files do not take"
	reasonNoPrompt         = "the command has no prompt"
	reasonText             = "the item is not valid UTF-8"
	reasonCredentialPath   = "%s matches the credential exclusion list"
	reasonSkillSummary     = "Gemini CLI does not load a skill without a description"
	reasonAgentDescription = "Gemini CLI does not load a subagent without a description"
)

var agentName = regexp.MustCompile(`^[a-z0-9_-]+$`)

type agentField struct {
	meta, name string
	accepts    func(any) bool
}

var agentFields = []agentField{
	{"gemini_display_name", "display_name", isText},
	{"gemini_tools", "tools", isTextList},
	{"gemini_model", "model", isText},
	{"gemini_temperature", "temperature", isNumber},
	{"gemini_max_turns", "max_turns", isPositiveInteger},
	{"gemini_timeout_mins", "timeout_mins", isPositiveInteger},
}

func agentFieldNamed(name string) (agentField, bool) {
	at := slices.IndexFunc(agentFields, func(f agentField) bool { return f.name == name })
	if at < 0 {
		return agentField{}, false
	}
	return agentFields[at], true
}

func isText(value any) bool {
	_, ok := value.(string)
	return ok
}

func isTextList(value any) bool {
	entries, ok := value.([]any)
	return ok && !slices.ContainsFunc(entries, func(entry any) bool { return !isText(entry) })
}

func isNumber(value any) bool {
	switch value.(type) {
	case int, float64:
		return true
	default:
		return false
	}
}

func isPositiveInteger(value any) bool {
	number, ok := value.(int)
	return ok && number > 0
}

func (ex *exporter) skill(it library.Item) {
	units, err := adapter.SkillUnits(ex.t, tool, it)
	if err != nil {
		ex.report(it, err.Error())
		return
	}
	for _, u := range units {
		if backup.Excluded(ex.t.Env, u.Path) {
			relative, _ := filepath.Rel(filepath.Join(ex.l.sharedSkills(), it.Name), u.Path)
			ex.report(it, fmt.Sprintf(reasonCredentialPath, "skill file "+filepath.ToSlash(relative)))
			return
		}
	}
	if strings.TrimSpace(it.Description) == "" {
		ex.report(it, reasonSkillSummary)
		return
	}
	ex.units = append(ex.units, units...)
}

func (ex *exporter) command(it library.Item) {
	var parts []string
	for _, part := range strings.Split(it.Name, commandSeparator) {
		if slug := library.Slug(part); slug != "" {
			parts = append(parts, slug)
		}
	}
	switch {
	case len(parts) == 0:
		ex.report(it, reasonNoFileName)
		return
	case strings.TrimSpace(it.Body) == "":
		ex.report(it, reasonNoPrompt)
		return
	case !utf8.ValidString(it.Description + it.Body):
		ex.report(it, reasonText)
		return
	}
	var document strings.Builder
	document.WriteString(generatedHeader)
	if it.Description != "" {
		fmt.Fprintf(&document, "%s = %s\n", descriptionKey, tomlString(it.Description))
	}
	fmt.Fprintf(&document, "%s = %s\n", promptKey, tomlMultiline(it.Body))
	parts[len(parts)-1] += tomlExtension
	path := ex.l.in(append([]string{commandsDir}, parts...)...)
	if !ex.document(it, path, []byte(document.String())) {
		return
	}
	var dropped []string
	for _, key := range it.MetaKeys() {
		if key != descriptionKey {
			dropped = append(dropped, key)
		}
	}
	ex.reportDropped(it, dropped, "command")
}

func (ex *exporter) subagent(it library.Item) {
	slug := library.Slug(it.Name)
	switch {
	case slug == "":
		ex.report(it, reasonNoFileName)
		return
	case strings.TrimSpace(it.Description) == "":
		ex.report(it, reasonAgentDescription)
		return
	}
	name := it.Name
	if !agentName.MatchString(name) {
		name = slug
	}
	header := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	set := func(key string, value any) error {
		keyNode, valueNode := &yaml.Node{}, &yaml.Node{}
		keyNode.SetString(key)
		if err := valueNode.Encode(value); err != nil {
			return fmt.Errorf("frontmatter %s: %w", key, err)
		}
		header.Content = append(header.Content, keyNode, valueNode)
		return nil
	}
	written := []string{nameKey, descriptionKey}
	err := set(nameKey, name)
	if err == nil {
		err = set(descriptionKey, it.Description)
	}
	for _, field := range agentFields {
		if value, present := it.Meta[field.meta]; err == nil && present && field.accepts(value) {
			err = set(field.name, value)
			written = append(written, field.meta)
		}
	}
	var content []byte
	if err == nil {
		content, err = renderMarkdown(header, it.Body)
	}
	if err != nil {
		ex.report(it, err.Error())
		return
	}
	if !ex.document(it, ex.l.in(agentsDir, slug+markdownExtension), content) {
		return
	}
	dropped := slices.DeleteFunc(it.MetaKeys(), func(key string) bool { return slices.Contains(written, key) })
	ex.reportDropped(it, dropped, "agent")
}

func renderMarkdown(header *yaml.Node, body string) ([]byte, error) {
	var buffer bytes.Buffer
	buffer.WriteString(frontmatterFence)
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)
	if err := encoder.Encode(header); err != nil {
		return nil, fmt.Errorf("frontmatter: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("frontmatter: %w", err)
	}
	buffer.WriteString(frontmatterFence)
	buffer.WriteString(body)
	return managed.WithNotice(buffer.Bytes()), nil
}

func (ex *exporter) document(it library.Item, path string, content []byte) bool {
	if backup.Excluded(ex.t.Env, path) {
		ex.report(it, fmt.Sprintf(reasonCredentialPath, filepath.Base(path)))
		return false
	}
	ex.add(plan.Unit{Path: path, Kind: manifest.UnitFile, Content: content, Items: []library.ID{it.ID}})
	return true
}

func (ex *exporter) reportDropped(it library.Item, keys []string, kind string) {
	if len(keys) == 0 {
		return
	}
	slices.Sort(keys)
	ex.report(it, fmt.Sprintf(reasonDropped, strings.Join(keys, ", "), kind))
}
