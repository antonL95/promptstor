package managed

import (
	"bytes"
	"errors"
	"slices"
)

const (
	Begin  = "<!-- promptstor:begin -->"
	End    = "<!-- promptstor:end -->"
	Notice = "<!-- Generated by PromptStor. Do not edit; change it with promptstor or the promptstor MCP tools. -->"
)

const (
	byteOrderMark = "\ufeff"
	fence         = "---"
)

var ErrMarkers = errors.New("unbalanced or duplicated promptstor markers")

type line struct {
	start, next int
	text        string
}

type span struct {
	begin, end line
}

func Section(doc []byte) ([]byte, bool, error) {
	found, ok, err := locate(doc)
	if err != nil || !ok {
		return nil, false, err
	}
	body := doc[found.begin.next:found.end.start]
	if first := lineAt(body, 0); first.text == Notice {
		body = body[first.next:]
	}
	return slices.Clone(body), true, nil
}

func SetSection(doc, body []byte) ([]byte, error) {
	found, ok, err := locate(doc)
	if err != nil {
		return nil, err
	}
	section, err := render(body)
	if err != nil {
		return nil, err
	}
	if ok {
		return slices.Concat(doc[:found.begin.start], section, doc[found.end.start+len(End):]), nil
	}
	return slices.Concat(doc, separator(doc), section, []byte("\n")), nil
}

func RemoveSection(doc []byte) ([]byte, error) {
	found, ok, err := locate(doc)
	if err != nil {
		return nil, err
	}
	if !ok {
		return slices.Clone(doc), nil
	}
	return slices.Concat(doc[:found.begin.start], doc[found.end.next:]), nil
}

func WithNotice(content []byte) []byte {
	at := noticeOffset(content)
	if lineAt(content, at).text == Notice {
		return slices.Clone(content)
	}
	head := slices.Clone(content[:at])
	if len(head) > textStart(content) && !bytes.HasSuffix(head, []byte("\n")) {
		head = append(head, '\n')
	}
	return slices.Concat(head, []byte(Notice+"\n"), content[at:])
}

func StripNotice(content []byte) []byte {
	at := noticeOffset(content)
	notice := lineAt(content, at)
	if notice.text != Notice {
		return slices.Clone(content)
	}
	return slices.Concat(content[:at], content[notice.next:])
}

func render(body []byte) ([]byte, error) {
	trimmed := bytes.TrimRight(body, "\r\n")
	section := []byte(Begin + "\n" + Notice + "\n" + string(trimmed) + "\n" + End)
	if _, _, err := locate(section); err != nil {
		return nil, err
	}
	return section, nil
}

func separator(doc []byte) []byte {
	switch {
	case len(doc) == textStart(doc):
		return nil
	case !bytes.HasSuffix(doc, []byte("\n")):
		return []byte("\n\n")
	case endsWithBlankLine(doc):
		return nil
	default:
		return []byte("\n")
	}
}

func endsWithBlankLine(doc []byte) bool {
	rest := bytes.TrimSuffix(doc[textStart(doc):], []byte("\n"))
	last := rest[bytes.LastIndexByte(rest, '\n')+1:]
	return len(bytes.TrimSpace(last)) == 0
}

func locate(doc []byte) (span, bool, error) {
	var begins, ends []line
	for at := textStart(doc); at < len(doc); {
		current := lineAt(doc, at)
		switch current.text {
		case Begin:
			begins = append(begins, current)
		case End:
			ends = append(ends, current)
		}
		at = current.next
	}
	if len(begins) == 0 && len(ends) == 0 {
		return span{}, false, nil
	}
	if len(begins) != 1 || len(ends) != 1 || ends[0].start < begins[0].start {
		return span{}, false, ErrMarkers
	}
	return span{begin: begins[0], end: ends[0]}, true, nil
}

func lineAt(doc []byte, start int) line {
	next := len(doc)
	if newline := bytes.IndexByte(doc[start:], '\n'); newline >= 0 {
		next = start + newline + 1
	}
	return line{start: start, next: next, text: string(bytes.TrimRight(doc[start:next], " \t\r\n"))}
}

func textStart(doc []byte) int {
	if bytes.HasPrefix(doc, []byte(byteOrderMark)) {
		return len(byteOrderMark)
	}
	return 0
}

func noticeOffset(content []byte) int {
	start := textStart(content)
	opening := lineAt(content, start)
	if opening.text != fence {
		return start
	}
	for at := opening.next; at < len(content); {
		current := lineAt(content, at)
		if current.text == fence {
			return current.next
		}
		at = current.next
	}
	return start
}
