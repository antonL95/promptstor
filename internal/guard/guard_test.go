func decide(t *testing.T, m manifest.Manifest, tool string, data []byte) (bool, string) {
	t.Helper()
	edits, err := guard.Parse(tool, data)
	if err != nil {
		t.Fatalf("parse %s payload: %v", tool, err)
	}
	return guard.Decide(m, edits)
}

func blockMessage(path string, id library.ID) string {
	return fmt.Sprintf("%s is generated by PromptStor. Change the library instead: use the promptstor_upsert MCP tool, or edit the item and run promptstor sync. Item: %s.", path, id)
}

func wantBlocked(t *testing.T, block bool, reason, path string, id library.ID) {
	t.Helper()
	if !block {
		t.Fatal("the edit was allowed, want it blocked")
	}
	if want := blockMessage(path, id); reason != want {
		t.Errorf("reason\n got %q\nwant %q", reason, want)
	}
}

func wantAllowed(t *testing.T, block bool, reason string) {
	t.Helper()
	if block {
		t.Fatalf("the edit was blocked: %s", reason)
	}
}

