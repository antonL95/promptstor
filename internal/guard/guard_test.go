func runHook(t *testing.T, env paths.Env, tool string, data []byte) (int, string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := guard.Run(tool, env.ManifestPath(), bytes.NewReader(data), &stdout, &stderr)
	return code, stdout.String(), stderr.String()
}

func saveManifest(t *testing.T, env paths.Env, m manifest.Manifest) {
	t.Helper()
	if err := os.MkdirAll(env.StateDir(), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := m.Save(env.ManifestPath()); err != nil {
		t.Fatal(err)
	}
}

func TestCorruptManifestFailsOpen(t *testing.T) {
	env, _ := fixture(t)
	if err := os.MkdirAll(env.StateDir(), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(env.ManifestPath(), []byte("{not json"), 0o600); err != nil {
		t.Fatal(err)
	}
	code, stdout, stderr := runHook(t, env, "claude-code", payload(t, env, "claude-code", "write-skill.json"))
	if code != 0 || stdout != "" {
		t.Errorf("exit %d with stdout %q, want exit 0 and no output", code, stdout)
	}
	if lines := strings.Count(stderr, "\n"); lines != 1 || !strings.HasPrefix(stderr, "promptstor hook: ") {
		t.Errorf("stderr %q, want one warning line", stderr)
	}
}

