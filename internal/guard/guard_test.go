func fixture(t *testing.T) (paths.Env, manifest.Manifest) {
	t.Helper()
	env := testenv.Home(t, "testdata/home")
	var m manifest.Manifest
	for _, o := range ownedUnits {
		path := filepath.Join(env.Home, o.path)
		doc, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		content, present, err := plan.ExtractUnit(o.unit, doc, o.key, true)
		if err != nil || !present {
			t.Fatalf("extract %s %s: present %v, %v", o.path, o.unit, present, err)
		}
		hash, err := manifest.Hash(o.unit, content)
		if err != nil {
			t.Fatal(err)
		}
		m.Put(manifest.Entry{
			Tool: o.tool, Path: path, Root: env.Home, Unit: o.unit, Key: o.key, Hash: hash,
			Items: []library.ID{o.item}, Written: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC),
		})
	}
	return env, m
}

