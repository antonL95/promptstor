package guard

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"slices"

	"github.com/antonL95/promptstor/internal/managed"
	"github.com/antonL95/promptstor/internal/manifest"
	"github.com/antonL95/promptstor/internal/plan"
)

const blockText = "%s is generated by PromptStor. Change the library instead: use the promptstor_upsert MCP tool, or edit the item and run promptstor sync."

func Decide(m manifest.Manifest, edits []Edit) (bool, string) {
	for _, e := range edits {
		if entry, blocked := decideEdit(m, e); blocked {
			return true, message(e.Path, entry)
		}
	}
	return false, ""
}

func decideEdit(m manifest.Manifest, e Edit) (manifest.Entry, bool) {
	entries := m.ForPath(e.Path)
	if len(entries) == 0 {
		return manifest.Entry{}, false
	}
	if at := slices.IndexFunc(entries, func(entry manifest.Entry) bool { return entry.Unit == manifest.UnitFile }); at >= 0 {
		return entries[at], true
	}
	if e.Opaque || e.Delete {
		return entries[0], true
	}
	if pathOnly(e) {
		return manifest.Entry{}, false
	}
	before, err := os.ReadFile(e.Path)
	exists := err == nil
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return manifest.Entry{}, false
	}
	steps := e.Steps
	if len(steps) == 0 {
		steps = []Edit{e}
	}
	doc, present := before, exists
	touchesSection := false
	for _, step := range steps {
		touchesSection = touchesSection || overlapsSection(doc, step.OldText)
		next, applies := apply(doc, present, step)
		if !applies {
			return manifest.Entry{}, false
		}
		doc, present = next, true
	}
	for _, entry := range entries {
		if entry.Unit == manifest.UnitSection && touchesSection {
			return entry, true
		}
		if unitChanges(entry, before, exists, doc) {
			return entry, true
		}
	}
	return manifest.Entry{}, false
}

func pathOnly(e Edit) bool {
	return e.WholeContent == nil && e.OldText == nil && e.NewText == nil && len(e.Steps) == 0
}

func apply(before []byte, exists bool, e Edit) ([]byte, bool) {
	switch {
	case e.WholeContent != nil:
		return e.WholeContent, true
	case len(e.OldText) == 0:
		return e.NewText, !exists
	case !bytes.Contains(before, e.OldText):
		return nil, false
	default:
		return bytes.ReplaceAll(before, e.OldText, e.NewText), true
	}
}

func overlapsSection(doc, old []byte) bool {
	begin := bytes.Index(doc, []byte(managed.Begin))
	end := bytes.Index(doc, []byte(managed.End))
	if len(old) == 0 || begin < 0 || end < begin {
		return false
	}
	end += len(managed.End)
	for from := 0; from < len(doc); {
		at := bytes.Index(doc[from:], old)
		if at < 0 {
			return false
		}
		start := from + at
		if start < end && start+len(old) > begin {
			return true
		}
		from = start + 1
	}
	return false
}

func unitChanges(entry manifest.Entry, before []byte, exists bool, after []byte) bool {
	was, wasPresent, err := plan.ExtractUnit(entry.Unit, before, entry.Key, exists)
	if err != nil {
		return false
	}
	now, nowPresent, err := plan.ExtractUnit(entry.Unit, after, entry.Key, true)
	if err != nil {
		return true
	}
	if wasPresent != nowPresent {
		return true
	}
	if !wasPresent {
		return false
	}
	wasHash, err := manifest.Hash(entry.Unit, was)
	if err != nil {
		return false
	}
	nowHash, err := manifest.Hash(entry.Unit, now)
	return err != nil || wasHash != nowHash
}

func message(path string, entry manifest.Entry) string {
	text := fmt.Sprintf(blockText, path)
	if len(entry.Items) > 0 {
		text += fmt.Sprintf(" Item: %s.", entry.Items[0])
	}
	return text
}

func WholeFiles(m manifest.Manifest, tools []string) []string {
	byPath := map[string][]manifest.Entry{}
	var order []string
	for _, entry := range m.Entries {
		if _, seen := byPath[entry.Path]; !seen {
			order = append(order, entry.Path)
		}
		byPath[entry.Path] = append(byPath[entry.Path], entry)
	}
	var whole []string
	for _, path := range order {
		entries := byPath[path]
		allFiles := !slices.ContainsFunc(entries, func(e manifest.Entry) bool { return e.Unit != manifest.UnitFile })
		selected := slices.ContainsFunc(entries, func(e manifest.Entry) bool {
			return slices.ContainsFunc(e.Tools(), func(tool string) bool { return slices.Contains(tools, tool) })
		})
		if allFiles && selected {
			whole = append(whole, path)
		}
	}
	slices.Sort(whole)
	return whole
}
